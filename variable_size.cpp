#include<iostream>
using namespace std;
int main(){
    int integer_type;
    float float_type;
    char character_type;
    double double_type;

    cout<<"The size of int: "<<sizeof(integer_type)<<endl;
    cout<<"The size of float: "<<sizeof(float_type)<<endl;
    cout<<"The size of char: "<<sizeof(character_type)<<endl;
    cout<<"The size of double: "<<sizeof(double_type)<<endl;

    return 0;
}